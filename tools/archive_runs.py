#!/usr/bin/env python
"""Build a deterministic index of experiment runs stored under ``out/``.

Why this exists
---------------
Run directories contain large per-case artifacts (plans, generated code, STEP
exports, events) that must not be committed.  The index is the small, reviewable
record that survives in git: it states which runs exist locally, how many cases
they completed, and which outcome distribution they produced.

Only the standard library is used, so the tool runs without the CAD environment.

Examples
--------
    python tools/archive_runs.py                       # regenerate defaults
    python tools/archive_runs.py --out out --check     # fail if index is stale
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

FORMAT = 'step2code-run-index'
VERSION = 1
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / 'out'
DEFAULT_JSON = ROOT / 'docs' / 'results' / 'index.json'
DEFAULT_MARKDOWN = ROOT / 'docs' / 'results' / 'runs.md'
OUTCOMES = ('accepted', 'incomplete', 'invalid_input', 'error')


def _read_json(path: Path):
    try:
        return json.loads(path.read_text(encoding='utf8'))
    except (OSError, ValueError):
        return None


def _dir_size_mb(path: Path) -> float:
    total = 0
    for root, _dirs, files in os.walk(path):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(root, name))
            except OSError:
                pass
    return round(total / (1024 * 1024), 1)


def _int(value):
    return value if isinstance(value, int) else None


def collect(out_root: Path):
    """Return (runs, skipped) sorted by run directory name."""
    runs, skipped = [], []
    if not out_root.is_dir():
        return runs, skipped
    for run_dir in sorted(p for p in out_root.iterdir() if p.is_dir()):
        if run_dir.name.startswith(('.', '__')):
            continue
        summary = _read_json(run_dir / 'summary.json')
        manifest = _read_json(run_dir / 'manifest.json')
        if summary is None and manifest is None:
            skipped.append(run_dir.name)
            continue
        summary = summary or {}
        manifest = manifest or {}
        counts = summary.get('counts') or {}
        runs.append({
            'name': run_dir.name,
            'run_state': summary.get('run_state') or manifest.get('run_state'),
            'requested': _int(summary.get('requested_count', manifest.get('requested_count'))),
            'selected': _int(summary.get('selected_count')),
            'completed': _int(summary.get('completed_count')),
            'counts': {key: int(counts[key]) for key in OUTCOMES if key in counts},
            'size_mb': _dir_size_mb(run_dir),
            'has_summary': bool(summary),
        })
    return runs, skipped


def build_index(out_root: Path) -> dict:
    runs, skipped = collect(out_root)
    return {
        'format': FORMAT,
        'version': VERSION,
        'source': 'out/',
        'runs': runs,
        'unindexed_directories': skipped,
    }


def render_markdown(index: dict) -> str:
    lines = [
        '# Run index',
        '',
        '<!-- Generated by tools/archive_runs.py; do not edit by hand. -->',
        '',
        '| run | state | requested | completed | accepted | incomplete | invalid_input | error | size (MB) |',
        '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    ]
    for run in index['runs']:
        counts = run['counts']
        cells = [
            f"`{run['name']}`",
            str(run['run_state'] or 'unknown'),
            '-' if run['requested'] is None else str(run['requested']),
            '-' if run['completed'] is None else str(run['completed']),
        ]
        cells += [str(counts.get(key, '-')) for key in OUTCOMES]
        cells.append(f"{run['size_mb']:.1f}")
        lines.append('| ' + ' | '.join(cells) + ' |')
    if index['unindexed_directories']:
        lines += ['', 'Directories without `summary.json` or `manifest.json` (probes/logs):', '']
        lines += [f"- `{name}`" for name in index['unindexed_directories']]
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description='Index experiment runs for archival')
    parser.add_argument('--out', type=Path, default=DEFAULT_OUT, help='run root (default: out/)')
    parser.add_argument('--json', type=Path, default=DEFAULT_JSON, help='index JSON output')
    parser.add_argument('--markdown', type=Path, default=DEFAULT_MARKDOWN, help='markdown table output')
    parser.add_argument('--check', action='store_true', help='verify outputs are current instead of writing')
    args = parser.parse_args(argv)

    index = build_index(args.out)
    payload = json.dumps(index, indent=2, sort_keys=False, ensure_ascii=False) + '\n'
    markdown = render_markdown(index)

    if args.check:
        stale = [str(path) for path, expected in ((args.json, payload), (args.markdown, markdown))
                 if not path.exists() or path.read_text(encoding='utf8') != expected]
        if stale:
            parser.error('stale archive index: ' + ', '.join(stale))
        print(f'index up to date: {len(index["runs"])} runs')
        return 0

    for path, text in ((args.json, payload), (args.markdown, markdown)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf8', newline='\n')
    print(f'indexed {len(index["runs"])} runs, {len(index["unindexed_directories"])} unindexed directories')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
